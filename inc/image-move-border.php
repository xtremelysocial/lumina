<?php
/**
 * Post-Process Core Images & Featured Images: Intercepts Global Styles and local 
 * design engine attributes to force uniform border containment onto interactive <a> link frames.
 */
add_filter( 'render_block_core/image', 'atmos_migrate_block_styles_to_link', 10, 2 );
add_filter( 'render_block_core/post-featured-image', 'atmos_migrate_block_styles_to_link', 10, 2 );

function atmos_migrate_block_styles_to_link( $block_content, $block ) {
	// 1. QUICK DEFENSIVE GATE: If there is no link wrapper, no clipping conflict exists
	if ( ! str_contains( $block_content, '<a ' ) ) {
		return $block_content;
	}

	// 2. STABILITY UPGRADE: Target the 'border' path directly inside the global style engine
	$global_border = null;
	if ( function_exists( 'wp_get_global_styles' ) && ! empty( $block['blockName'] ) ) {
		$global_border = wp_get_global_styles( array( 'border' ), array( 'block_name' => $block['blockName'] ) );
	}

	// 3. EXTRACT INSTANCE STYLES: Fetch specific settings applied directly to this block item
	$local_border = isset( $block['attrs']['style']['border'] ) ? $block['attrs']['style']['border'] : null;

	// 4. THE DATA MERGE: Deep merge local block configurations over global stylesheet settings
	$border_data = array_replace_recursive( (array) $global_border, (array) $local_border );
	if ( empty( $border_data ) ) {
		return $block_content;
	}

	$compiled_styles = array();

	// Helper function to safely map block-editor design tokens straight to native variables
	$normalize_color = function( $color ) {
		if ( is_string( $color ) && str_contains( $color, 'var:preset|color|' ) ) {
			$slug = str_replace( 'var:preset|color|', '', $color );
			return "var(--wp--preset--color--{$slug})";
		}
		return $color;
	};

	// 5. EXTRACT RADIUS PROFILES (Uniform or Split camelCase corners)
	if ( isset( $border_data['radius'] ) ) {
		if ( is_array( $border_data['radius'] ) ) {
			foreach ( $border_data['radius'] as $corner => $value ) {
				$kebab_corner = strtolower( preg_replace( '/(?<!^)[A-Z]/', '-$0', $corner ) );
				$compiled_styles[] = "border-{$kebab_corner}-radius: {$value}";
			}
		} else {
			$compiled_styles[] = "border-radius: " . $border_data['radius'];
		}
	}

	// 6. EXTRACT UNIFORM BORDERS
	if ( isset( $border_data['width'] ) ) {
		$compiled_styles[] = "border-width: " . $border_data['width'];
	}
	if ( isset( $border_data['style'] ) ) {
		$compiled_styles[] = "border-style: " . $border_data['style'];
	}
	if ( isset( $border_data['color'] ) ) {
		$compiled_styles[] = "border-color: " . $normalize_color( $border_data['color'] );
	}

	// 7. EXTRACT SPLIT SIDE BORDERS (Top, Right, Bottom, Left arrays generated by core layout engines)
	$sides = array( 'top', 'right', 'bottom', 'left' );
	foreach ( $sides as $side ) {
		if ( isset( $border_data[$side] ) ) {
			if ( isset( $border_data[$side]['width'] ) ) {
				$compiled_styles[] = "border-{$side}-width: " . $border_data[$side]['width'];
			}
			if ( isset( $border_data[$side]['style'] ) ) {
				$compiled_styles[] = "border-{$side}-style: " . $border_data[$side]['style'];
			}
			if ( isset( $border_data[$side]['color'] ) ) {
				$compiled_styles[] = "border-{$side}-color: " . $normalize_color( $border_data[$side]['color'] );
			}
		}
	}

	// 8. SURGICAL INJECTION: Map compiled payload rules directly onto the first <a> viewport link node
	if ( ! empty( $compiled_styles ) ) {
		$processor = new WP_HTML_Tag_Processor( $block_content );
		if ( $processor->next_tag( array( 'tag_name' => 'a' ) ) ) {
			$existing_styles = $processor->get_attribute( 'style' );
			$new_styles = trim( $existing_styles . '; ' . implode( '; ', $compiled_styles ), '; ' );
			
			$processor->set_attribute( 'style', $new_styles . ';' );
			$block_content = $processor->get_updated_html();
		}
	}

	return $block_content;
}